#!/usr/bin/env sh
# Report what loads into an agent's context, from where, and what is broken.
# Reads only. Writes nothing.

HOME_DIR="$(cd "$(dirname "$0")/.." && pwd)"
tilde() { echo "$1" | sed "s|^$HOME|~|"; }

echo "home: $(tilde "$HOME_DIR")"
if git -C "$HOME_DIR" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
  b=$(git -C "$HOME_DIR" rev-parse --abbrev-ref HEAD)
  s=$(git -C "$HOME_DIR" rev-parse --short HEAD)
  d=$(git -C "$HOME_DIR" status --porcelain | wc -l | tr -d ' ')
  echo "  $b at $s, $d uncommitted"
  git -C "$HOME_DIR" rev-parse --verify -q upstream/main >/dev/null 2>&1 &&
    echo "  behind upstream by $(git -C "$HOME_DIR" rev-list --count HEAD..upstream/main) commits"
else
  echo "  NOT a git checkout. You cannot see what you changed."
fi

# merge=ours without the driver set falls back to a normal merge, silently.
if [ -f "$HOME_DIR/.gitattributes" ] && grep -q 'merge=ours' "$HOME_DIR/.gitattributes" 2>/dev/null; then
  if [ "$(git -C "$HOME_DIR" config merge.ours.driver)" != "true" ]; then
    echo "  .gitattributes marks files merge=ours but merge.ours.driver is unset."
    echo "  Those files will conflict on every upstream change. Fix:"
    echo "    git -C $(tilde "$HOME_DIR") config merge.ours.driver true"
  fi
fi

echo
echo "always-on (loads every session):"
total=0
for f in "$HOME_DIR/principles.md" "$HOME_DIR"/rules/*.md; do
  [ -e "$f" ] || continue
  n=$(wc -c < "$f" | tr -d ' ')
  total=$((total + n))
  echo "  $(basename "$f")  ${n} bytes"
done
echo "  total ${total} bytes"

echo
echo "on demand (the router names these; opened when a task matches):"
for d in memory templates skills decisions standards context; do
  [ -d "$HOME_DIR/$d" ] || continue
  echo "  $d/  $(find "$HOME_DIR/$d" -type f | wc -l | tr -d ' ') files"
done

# An import line that resolves to nothing is the failure this report exists for.
report_file() {
  f="$1"; label="$2"; cap="$3"
  if [ ! -e "$f" ]; then
    echo
    echo "$label: no file at $(tilde "$f"). This harness loads nothing from here."
    return 0
  fi
  echo
  echo "$label: $(tilde "$f")"
  mine=0; foreign=0; broken=0
  while IFS= read -r line; do
    case "$line" in
      @*) p=$(echo "$line" | sed 's/^@//; s|^~|'"$HOME"'|')
          if [ ! -e "$p" ]; then
            echo "  BROKEN $line"; broken=$((broken + 1))
          else
            case "$p" in "$HOME_DIR"/*) mine=$((mine + 1)) ;; *) foreign=$((foreign + 1)) ;; esac
          fi ;;
    esac
  done < "$f"
  own=$(wc -l < "$f" | tr -d ' ')
  bytes=$(wc -c < "$f" | tr -d ' ')
  [ -L "$f" ] && echo "  symlink -> $(tilde "$(readlink "$f")")"
  echo "  $own lines, $bytes bytes: $mine imports from this home, $foreign from elsewhere, $broken broken"
  # Codex compares global plus thread instructions against project_doc_max_bytes
  # and warns, but truncates only project files. Crossing it is a signal, not a
  # cut-off. Source: codex-rs/core/src/agents_md_manager.rs. Codex follows no
  # import, so this file is all it loads from the home: wire already copied the
  # always-on set into it.
  if [ -n "$cap" ] && [ "$bytes" -gt "$cap" ]; then
    echo "  $bytes bytes, over the $cap byte"
    echo "  project_doc_max_bytes setting. This file is not truncated, but the"
    echo "  harness warns, and project files then compete for what is left."
  fi
  # Content in the file itself outranks nothing and duplicates the home.
  # grep -c exits 1 on no match, so `|| echo 0` would append a second count.
  body=$(grep -cvE '^[[:space:]]*$|^@|^<!--' "$f" 2>/dev/null) || body=0
  if [ "$body" -gt 10 ] && ! head -1 "$f" | grep -q 'owns this file'; then
    echo "  $body lines of rules live in this file, not in the home. Two sources of truth."
  fi
  grep -n 'Generated from\|generated by\|do not edit' "$f" 2>/dev/null | head -2 |
    while IFS= read -r g; do echo "  OWNED BY A GENERATOR: $g"; echo "  A regeneration will discard anything added here."; done
}

echo
echo "what each harness loads:"
report_file "$HOME/.claude/rules/00-agents-home.md" "claude code, the home's drop-in" ""
report_file "$HOME/.claude/CLAUDE.md" "claude code, the harness's own file" ""
report_file "${CODEX_HOME:-$HOME/.codex}/AGENTS.md" "codex" 32768
# Cursor keeps user-level rules in its application settings, not in a file, so
# nothing here can read or wire them. Project rules are per repository.
if [ -d "$HOME/.cursor" ]; then
  echo
  echo "cursor: user rules live in the app settings, not a file."
  echo "  Nothing here can read or wire them. Paste the pointer line by hand:"
  echo "    Read ~/.agents/AGENTS.md and every file in ~/.agents/rules/ before starting work."
fi

# A hook naming a path that is gone blocks the tool it guards, and the error
# names the script rather than the config that still calls for it.
SETTINGS="$HOME/.claude/settings.json"
if [ -f "$SETTINGS" ]; then
  # A command may name a path as /abs, $HOME/x, ${HOME}/x or ~/x. Expand all
  # four before testing, or the check passes on paths it never looked at.
  gone=$(grep -oE '"command"[[:space:]]*:[[:space:]]*"[^"]*"' "$SETTINGS" 2>/dev/null |
         sed 's/.*:[[:space:]]*"//; s/"$//' |
         tr ' ' '\n' |
         sed "s|^\\\$HOME/|$HOME/|; s|^\\\${HOME}/|$HOME/|; s|^~/|$HOME/|" |
         grep -E '^/' |
         while read -r t; do [ -e "$t" ] || echo "$t"; done | sort -u)
  if [ -n "$gone" ]; then
    echo
    echo "hooks in $(tilde "$SETTINGS") naming a path that does not exist:"
    echo "$gone" | while read -r t; do echo "  $(tilde "$t")"; done
    echo "  Each one fails the tool it guards. Remove the hook or restore the file."
  fi
fi

echo
echo "links into this home:"
found=0
for l in "$HOME/.claude/rules/agents" "$HOME/.claude/skills/agents"; do
  [ -L "$l" ] || continue
  found=1
  t=$(readlink "$l")
  [ -e "$l" ] && echo "  $(tilde "$l") -> $(tilde "$t")" || echo "  BROKEN $(tilde "$l") -> $t"
done
[ "$found" -eq 1 ] || echo "  none"
